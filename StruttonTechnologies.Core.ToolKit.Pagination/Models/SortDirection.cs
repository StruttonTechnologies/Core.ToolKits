namespace StruttonTechnologies.Core.ToolKit.Pagination
{
    /// <summary>
    /// Specifies the direction in which to sort data.
    /// </summary>
    public enum SortDirection
    {
        /// <summary>
        /// Sort in ascending order (A to Z, 0 to 9, earliest to latest).
        /// </summary>
        Ascending = 0,

        /// <summary>
        /// Sort in descending order (Z to A, 9 to 0, latest to earliest).
        /// </summary>
        Descending = 1
    }
}
